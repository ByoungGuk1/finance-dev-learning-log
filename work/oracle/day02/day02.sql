-- OUTER JOIN

-- LEFT JOIN : 기준 테이블은 모두 출력
SELECT EMPLOYEES.EMAIL, DEPARTMENTS.DEPARTMENT_NAME
FROM EMPLOYEES
LEFT JOIN DEPARTMENTS
ON EMPLOYEES.DEPARTMENT_ID = DEPARTMENTS.DEPARTMENT_ID
ORDER BY DEPARTMENTS.DEPARTMENT_NAME NULLS FIRST;

-- RIGHT JOIN : 참조 테이블 모두 출력
SELECT EMPLOYEES.EMAIL, DEPARTMENTS.DEPARTMENT_NAME
FROM EMPLOYEES
RIGHT JOIN DEPARTMENTS
ON EMPLOYEES.DEPARTMENT_ID = DEPARTMENTS.DEPARTMENT_ID
ORDER BY EMPLOYEES.EMAIL NULLS FIRST;

-- FULL OUTER JOIN : 모든 테이블 출력
SELECT EMPLOYEES.EMAIL, DEPARTMENTS.DEPARTMENT_NAME
FROM EMPLOYEES
FULL JOIN DEPARTMENTS
ON EMPLOYEES.DEPARTMENT_ID = DEPARTMENTS.DEPARTMENT_ID
ORDER BY EMPLOYEES.EMAIL NULLS FIRST;



-- 벤더 문법
SELECT EMPLOYEES.FIRST_NAME,
    DEPARTMENTS.DEPARTMENT_NAME,
    LOCATIONS.CITY,
    COUNTRIES.COUNTRY_NAME,
    REGIONS.REGION_NAME
FROM EMPLOYEES, DEPARTMENTS, LOCATIONS, COUNTRIES, REGIONS
WHERE EMPLOYEES.DEPARTMENT_ID = DEPARTMENTS.DEPARTMENT_ID
    AND DEPARTMENTS.LOCATION_ID = LOCATIONS.LOCATION_ID
    AND LOCATIONS.COUNTRY_ID = COUNTRIES.COUNTRY_ID
    AND COUNTRIES.REGION_ID = REGIONS.REGION_ID;

