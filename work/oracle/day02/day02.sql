-- 부서별 직원들의 급여 합계
SELECT D.DEPARTMENT_NAME AS "부서명", SUM(E.SALARY) AS "급여 합계", COUNT(*) AS "직원수"
FROM EMPLOYEES E
JOIN DEPARTMENTS D ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
GROUP BY D.DEPARTMENT_NAME
HAVING SUM(E.SALARY) > 50000
ORDER BY "급여 합계" DESC;



