-- CASE WHEN (= Java의 switch)
-- CASE WHEN 단순 형식 (DECODE와 동일한 기능)
SELECT EMPLOYEE_ID,
       SALARY,
       CASE JOB_ID
         WHEN 'AD_PRES' THEN '임원'
         WHEN 'AD_VP'   THEN '부사장'
         WHEN 'IT_PROG' THEN 'IT개발자'
         ELSE '기타'
       END AS 직무구분,
       CASE
         WHEN JOB_ID LIKE 'AD%' THEN '임원'
         WHEN JOB_ID LIKE 'AD%' THEN '부사장' -- 같은 조건이라면 먼저 오는 값
         WHEN JOB_ID LIKE 'IT%' THEN 'IT개발자'
         ELSE '기타'
       END AS 직무구분
FROM   EMPLOYEES
WHERE  DEPARTMENT_ID IN (90, 60);

-- CASE WHEN 검색 형식 (범위 조건 가능)
SELECT EMPLOYEE_ID,
       SALARY,
       CASE
         WHEN SALARY >= 15000 THEN 'S등급'
         WHEN SALARY >= 10000 THEN 'A등급'
         WHEN SALARY >=  5000 THEN 'B등급'
         ELSE 'C등급'
       END AS 급여등급
FROM   EMPLOYEES
ORDER  BY SALARY DESC;

-- SALARY 10000 이상이면 급여(상), 5000 이상이면 중, 기타 하
SELECT EMPLOYEE_ID AS ID,
    CASE 
        WHEN SALARY >= 10000 THEN '상'
        WHEN SALARY >= 5000 THEN '중'
        ELSE '하'
    END AS "급여등급"
FROM EMPLOYEES
WHERE  DEPARTMENT_ID IN (90, 60)
ORDER BY SALARY DESC;

-- FIRST_NAME 의 길이를 판단해서 10자리 이상'Long', 5자리 이상'Middle', 그 외'Short'
SELECT FIRST_NAME,
    CASE
        WHEN LENGTH(FIRST_NAME) >= 10 THEN 'Long'
        WHEN LENGTH(FIRST_NAME) >= 5 THEN 'Middle'
        ELSE 'Short'
    END AS "이름 길이"
FROM EMPLOYEES
ORDER BY LENGTH(FIRST_NAME) DESC;

