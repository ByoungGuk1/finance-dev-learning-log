-- **SELECT 절에 그룹 함수 외 컬럼이 있으면 모두 GROUP BY에 포함**
-- 부서별 급여의 합계와 직원수
SELECT DEPARTMENT_ID, COUNT(*), SUM(SALARY)
FROM EMPLOYEES
GROUP BY ROLLUP(DEPARTMENT_ID) --ROLLUP 전체의 값 출력
ORDER BY 1 NULLS FIRST;

-- 직급별 급여의 합계와 직원수
SELECT JOB_ID, SUM(SALARY), COUNT(*) AS "인원"    --5
FROM EMPLOYEES  --1
WHERE SALARY > 0    --2
GROUP BY JOB_ID     --3
HAVING COUNT(*) >= 5    --4
ORDER BY 3 DESC NULLS LAST; --6

-- 부서별, 직급별 급여의 합계와 직원수
SELECT DEPARTMENT_ID AS "부서ID", 
    CASE GROUPING(JOB_ID)
        WHEN 1 
            THEN 
                CASE GROUPING(DEPARTMENT_ID)
                    WHEN 1 THEN '총합'
                    ELSE '부서별 합계'
                END    
        ELSE JOB_ID
    END AS "JOB_ID",
    SUM(SALARY), COUNT(*),
    GROUPING(DEPARTMENT_ID) AS "부서합", GROUPING(JOB_ID) AS "직무합"
FROM EMPLOYEES
WHERE DEPARTMENT_ID IS NOT NULL
GROUP BY ROLLUP(DEPARTMENT_ID, JOB_ID)
ORDER BY 1,2;

